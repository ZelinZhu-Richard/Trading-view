import { browserExecutable, evidenceDirectory } from './browser-runtime.mjs';
import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir(evidenceDirectory, { recursive: true });
const browser = await chromium.launch({ executablePath: browserExecutable, headless: true });
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
const page = await context.newPage();
page.setDefaultTimeout(20000);
const base = 'http://127.0.0.1:8000/api', headers = { 'X-Workbench-Request': '1' };
const original = await (await context.request.get(base+'/workspaces/default')).json();
const stamp = Date.now(), ids = [], jobs = [], errors = [];
page.on('pageerror', error => errors.push(error.message));
const script = (name, source) => ({ schema_version: 1, id: crypto.randomUUID(), name, kind: 'strategy', source, parameters: {}, subscriptions: [], revision: 0 });
const normal = script(`Research browser ${stamp}`, 'PARAMETERS = {"quantity": {"type": "int", "default": 1, "minimum": 1}}\n\ndef initialize(ctx):\n    ctx.order(ctx.subscriptions[0], "buy", ctx.parameters["quantity"])\n\ndef on_bars(ctx, bars):\n    if not ctx.state.get("sold"):\n        ctx.order(ctx.subscriptions[0], "sell", ctx.parameters["quantity"])\n        ctx.state["sold"] = True\n    ctx.log("complete", ctx.timestamp)');
const infinite = script(`Cancel browser ${stamp}`, 'def on_bars(ctx, bars):\n    while True:\n        pass');
try {
  const dataset = await (await context.request.post(base+'/examples/dataset', { headers })).json();
  await context.request.put(base+'/workspaces/default', { headers, data: { ...original, bottom_open: true, bottom_height: 450, layout: 1, active_chart: 0, charts: original.charts.map(c => ({ ...c, dataset_id: dataset.id, indicators: [], drawings: [] })) } });
  for (const value of [infinite, normal]) { const response = await context.request.put(base+`/scripts/${value.id}`, { headers, data: value }); if (!response.ok()) throw new Error(await response.text()); ids.push(value.id); }
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('button', { name: 'Python editor', exact: true }).click();
  await page.getByLabel('Saved Python script').selectOption(normal.id);
  await expect(page.getByText('Syntax and declarations valid', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Run settings', exact: true }).click();
  await page.getByLabel('Parameter quantity', { exact: true }).fill('2');
  await page.getByLabel('Allow labeled synthetic demonstration data').check();
  const create = page.waitForResponse(response => response.url().endsWith('/api/research') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run', exact: true }).click();
  const first = await (await create).json(); jobs.push(first.id);
  await expect(page.locator('.job-status')).toHaveText('completed', { timeout: 30000 });
  await expect(page.locator('.metric-grid')).toContainText('total return');
  const result = await (await context.request.get(base+`/research/${first.id}/result`)).json();
  if (result.fills.length !== 2 || Number(result.fills[0].quantity) !== 2) throw new Error('Parameter or accounting result mismatch');
  await page.screenshot({ path: `${evidenceDirectory}/research-results.png` });
  await page.getByRole('button', { name: 'fills', exact: true }).click();
  await expect(page.locator('.research-table tbody tr')).toHaveCount(2);
  const exportEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export fills CSV', exact: true }).click();
  const stream = await (await exportEvent).createReadStream(); let csv = ''; for await (const chunk of stream) csv += chunk.toString();
  if (!csv.includes('fill-1') || !csv.includes('fill-2')) throw new Error('CSV export lost fill records');
  await page.getByRole('button', { name: 'logs', exact: true }).click();
  await expect(page.locator('.research-logs')).toContainText('complete');
  await page.getByRole('button', { name: 'inputs', exact: true }).click();
  await expect(page.locator('.research-inputs')).toContainText('script_hash');
  await page.getByLabel(`Compare ${normal.name} run`, { exact: true }).check();
  await expect(page.locator('.research-comparison')).toContainText('USD');
  await page.getByRole('button', { name: 'Python editor', exact: true }).click();
  await page.getByLabel('Saved Python script').selectOption(infinite.id);
  await expect(page.getByText('Syntax and declarations valid', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Run settings', exact: true }).click();
  await page.getByLabel('Allow labeled synthetic demonstration data').check();
  const createSlow = page.waitForResponse(response => response.url().endsWith('/api/research') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Run', exact: true }).click();
  const slow = await (await createSlow).json(); jobs.push(slow.id);
  await expect(page.locator('.job-status')).toHaveText('running');
  const interactionStart = performance.now();
  await page.getByLabel('Chart type', { exact: true }).selectOption('line');
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  const interactionMs = performance.now()-interactionStart;
  const cancelStart = performance.now();
  await page.getByRole('button', { name: 'Cancel run', exact: true }).click();
  await expect(page.locator('.job-status')).toHaveText('cancelled');
  const cancellationMs = performance.now()-cancelStart;
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.screenshot({ path: `${evidenceDirectory}/research-cancel-light-1280.png` });
  await page.reload();
  await page.getByRole('button', { name: 'Research results', exact: true }).click();
  await expect(page.locator('.research-runs')).toContainText(normal.name);
  await page.locator('.research-runs button').filter({ hasText: normal.name }).click();
  await expect(page.locator('.job-status')).toHaveText('completed');
  if (errors.length) throw new Error(JSON.stringify(errors));
  const report = { status: 'passed', date: new Date().toISOString(), browser: await browser.version(), jobs,
    results: ['Explicit Run settings and generated parameters; completed result, fill table, CSV export, logs, immutable input inspection, comparison, reload, active-job chart interaction and cancellation passed.'],
    interactionMs, cancellationMs, pageErrors: errors, limitations: ['Synthetic test prices; not a market-performance claim. Replay and paper mode are outside this check.'] };
  await writeFile(`${evidenceDirectory}/research-report.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} catch (error) {
  await page.screenshot({ path: `${evidenceDirectory}/research-failure.png` });
  await writeFile(`${evidenceDirectory}/research-report.json`, JSON.stringify({ status: 'failed', date: new Date().toISOString(), error: error.message, jobs, pageErrors: errors }, null, 2));
  throw error;
} finally {
  await page.close();
  for (const id of jobs) await context.request.post(base+`/research/${id}/cancel`, { headers });
  for (const id of ids) await context.request.delete(base+`/scripts/${id}`, { headers });
  const latest = await (await context.request.get(base+'/workspaces/default')).json();
  await context.request.put(base+'/workspaces/default', { headers, data: { ...original, revision: latest.revision } });
  await browser.close();
}
